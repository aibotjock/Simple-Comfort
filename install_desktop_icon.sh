#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Simple-Comfort — Desktop Icon Installer
# Supports: GNOME, KDE Plasma, XFCE, generic XDG desktops on Linux/macOS
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_NAME="Simple-Comfort"
DESKTOP_FILE="simple-comfort.desktop"
ICON_SRC="$SCRIPT_DIR/static/icon.png"
ICON_256="$SCRIPT_DIR/static/icon-256.png"

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  $APP_NAME  —  Desktop Icon Installer"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

# ── 1. Detect OS ──────────────────────────────────────────────────────────────
OS="$(uname -s)"

if [[ "$OS" == "Darwin" ]]; then
    # ── macOS ─────────────────────────────────────────────────────────────────
    echo "[macOS] Creating application bundle in ~/Applications ..."
    BUNDLE="$HOME/Applications/Simple-Comfort.app"
    mkdir -p "$BUNDLE/Contents/MacOS"
    mkdir -p "$BUNDLE/Contents/Resources"

    # Launcher script inside the bundle
    cat > "$BUNDLE/Contents/MacOS/simple-comfort" <<EOF
#!/usr/bin/env bash
cd "$SCRIPT_DIR"
exec python3 app.py
EOF
    chmod +x "$BUNDLE/Contents/MacOS/simple-comfort"

    # Info.plist
    cat > "$BUNDLE/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key>    <string>simple-comfort</string>
    <key>CFBundleIdentifier</key>   <string>local.simple-comfort</string>
    <key>CFBundleName</key>         <string>Simple-Comfort</string>
    <key>CFBundleVersion</key>      <string>1.0</string>
    <key>CFBundleIconFile</key>     <string>icon</string>
    <key>LSUIElement</key>          <false/>
    <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
EOF

    # Convert PNG to ICNS if sips is available
    if command -v sips &>/dev/null && command -v iconutil &>/dev/null; then
        ICONSET="$BUNDLE/Contents/Resources/icon.iconset"
        mkdir -p "$ICONSET"
        for sz in 16 32 64 128 256 512; do
            sips -z $sz $sz "$ICON_SRC" --out "$ICONSET/icon_${sz}x${sz}.png" &>/dev/null
            sips -z $((sz*2)) $((sz*2)) "$ICON_SRC" --out "$ICONSET/icon_${sz}x${sz}@2x.png" &>/dev/null
        done
        iconutil -c icns "$ICONSET" -o "$BUNDLE/Contents/Resources/icon.icns"
        rm -rf "$ICONSET"
        echo "  ✔ ICNS icon created"
    else
        cp "$ICON_SRC" "$BUNDLE/Contents/Resources/icon.png"
        echo "  ✔ PNG icon placed (install sips for ICNS conversion)"
    fi

    # Dock alias
    if [ -d "$HOME/Desktop" ]; then
        ln -sf "$BUNDLE" "$HOME/Desktop/Simple-Comfort.app" 2>/dev/null || true
        echo "  ✔ Alias placed on Desktop"
    fi

    # Touch so Finder picks up changes
    touch "$BUNDLE"
    echo "  ✔ Bundle created: $BUNDLE"
    echo ""
    echo "  Open Simple-Comfort from ~/Applications or your Desktop."
    echo "  First launch: right-click → Open to bypass Gatekeeper."

elif [[ "$OS" == "Linux" ]]; then
    # ── Linux (XDG) ───────────────────────────────────────────────────────────

    # Install icon into XDG icon theme
    ICON_DIR="$HOME/.local/share/icons/hicolor"
    mkdir -p "$ICON_DIR/512x512/apps" "$ICON_DIR/256x256/apps" "$ICON_DIR/128x128/apps"
    cp "$ICON_SRC"  "$ICON_DIR/512x512/apps/simple-comfort.png"
    cp "$ICON_256"  "$ICON_DIR/256x256/apps/simple-comfort.png"
    python3 -c "
from PIL import Image
img = Image.open('$ICON_SRC')
img.resize((128,128)).save('$ICON_DIR/128x128/apps/simple-comfort.png')
" 2>/dev/null || cp "$ICON_SRC" "$ICON_DIR/128x128/apps/simple-comfort.png"
    gtk-update-icon-cache "$ICON_DIR" 2>/dev/null || true
    echo "  ✔ Icons installed to $ICON_DIR"

    # Write an explicit, executable launcher wrapper in the app directory.
    # Using a real script as the Exec target is more reliable than an inline
    # `bash -c '...'` string, which some desktop environments mishandle.
    LAUNCHER="$SCRIPT_DIR/simple-comfort-launch.sh"
    cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Auto-generated by install_desktop_icon.sh — launches Simple-Comfort.
cd "$SCRIPT_DIR"
if [ -d "$SCRIPT_DIR/venv" ]; then
    # shellcheck disable=SC1091
    source "$SCRIPT_DIR/venv/bin/activate"
fi
exec python3 app.py
EOF
    chmod +x "$LAUNCHER"
    echo "  ✔ Launcher wrapper created: $LAUNCHER"

    # Write the .desktop file, pointing Exec at the launcher wrapper.
    DESKTOP_DEST="$HOME/.local/share/applications/$DESKTOP_FILE"
    cat > "$DESKTOP_DEST" <<EOF
[Desktop Entry]
Version=1.0
Type=Application
Name=Simple-Comfort
GenericName=AI Video Generator
Comment=Generate 30-second AI video clips locally with LTX-2.3, Wan 2.2, or FramePack
Exec=$LAUNCHER
Icon=simple-comfort
Terminal=false
StartupNotify=true
StartupWMClass=simple-comfort
Categories=AudioVideo;Video;
Keywords=AI;Video;ComfyUI;Generation;
EOF
    chmod +x "$DESKTOP_DEST"
    update-desktop-database "$HOME/.local/share/applications" 2>/dev/null || true
    echo "  ✔ .desktop entry installed: $DESKTOP_DEST"

    # Also place on Desktop if it exists
    DESKTOP_DIR="$HOME/Desktop"
    if [ -d "$DESKTOP_DIR" ]; then
        cp "$DESKTOP_DEST" "$DESKTOP_DIR/$DESKTOP_FILE"
        chmod +x "$DESKTOP_DIR/$DESKTOP_FILE"
        # Trust the desktop file (GNOME)
        gio set "$DESKTOP_DIR/$DESKTOP_FILE" metadata::trusted true 2>/dev/null || true
        echo "  ✔ Icon placed on Desktop: $DESKTOP_DIR/$DESKTOP_FILE"
    fi

    echo ""
    echo "  Simple-Comfort is now in your application menu."
    echo "  If the desktop icon shows as text, right-click → Allow Launching."

else
    echo "  [!] Unsupported OS: $OS"
    echo "  On Windows, run install_desktop_icon.bat instead."
    exit 1
fi

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Done. Launch Simple-Comfort, then"
echo "  open http://localhost:7788 in your browser."
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
